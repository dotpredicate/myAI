"""Hybrid integration tests: Mock Model -> Real Tool execution.

Verifies that tool calls generated by a mocked inference provider
are correctly executed by the real tool system.
"""
import json
from pathlib import Path

from tests.helpers import BaseTestCase, Yield
from backend.inference.engine import FinishedToolCall


class TestHybridFlow(BaseTestCase):

    async def test_mock_model_triggers_real_shell_command(self):
        """Mock issues bash -> real subprocess executes it."""
        self.mock_provider.schedule_stream(
            Yield(finished=FinishedToolCall(
                name="bash",
                parameters=json.dumps({"command": "echo hello-world"}),
            )),
        )

        resp = await self._helper_prompt("run a command", model_id="m")
        self.assertEqual(resp.status_code, 200)

        conv_id = int(resp.headers["x-conversation-id"])
        conv = (await self.client.get(f"/api/conversations/{conv_id}")).json()

        tool_calls = [m for m in conv["messages"] if m["element"]["type"] == "tool_call"]
        self.assertGreaterEqual(len(tool_calls), 1)

        result = json.loads(tool_calls[-1]["element"]["result"])
        self.assertEqual(result["returncode"], 0)
        self.assertIn("hello-world", result["stdout"])

    async def test_mock_model_parameter_passing(self):
        """Verify mock parameters are correctly passed to the real tool."""
        self.mock_provider.schedule_stream(
            Yield(finished=FinishedToolCall(
                name="bash",
                parameters=json.dumps({"command": "echo arg1 arg2"}),
            )),
        )

        resp = await self._helper_prompt("do it", model_id="m")
        self.assertEqual(resp.status_code, 200)

        conv_id = int(resp.headers["x-conversation-id"])
        conv = (await self.client.get(f"/api/conversations/{conv_id}")).json()

        tool_calls = [m for m in conv["messages"] if m["element"]["type"] == "tool_call"]
        result = json.loads(tool_calls[-1]["element"]["result"])
        self.assertEqual(result["stdout"].strip(), "arg1 arg2")

    async def test_mock_model_triggers_replace_file(self):
        """Mock issues replace_file -> system generates a real proposal."""
        repo_name = await self._helper_repo_source()

        source_rel = "source.txt"
        Path(self._repo_dir.name, "target.txt").write_text("old content", encoding="utf-8")

        self.mock_provider.schedule_stream(
            Yield(finished=FinishedToolCall(
                name="bash",
                parameters=json.dumps({"command": f"printf 'new content' > /workspace/{source_rel}"}),
            )),
            Yield(finished=FinishedToolCall(
                name="replace_file",
                parameters=json.dumps({
                    "target": f"/repositories/{repo_name}/target.txt",
                    "source": f"/workspace/{source_rel}",
                }),
            )),
        )

        resp = await self._helper_prompt("replace the file", model_id="m")
        self.assertEqual(resp.status_code, 200)

        conv_id = int(resp.headers["x-conversation-id"])
        conv = (await self.client.get(f"/api/conversations/{conv_id}")).json()

        tool_calls = [m for m in conv["messages"] if m["element"]["type"] == "tool_call"]
        self.assertGreaterEqual(len(tool_calls), 1)

        result = json.loads(tool_calls[-1]["element"]["result"])
        self.assertEqual(result["type"], "replace_proposal")
        self.assertEqual(result["status"], "pending")

        approval_requests = [m for m in conv["messages"] if m["element"]["type"] == "approval_request"]
        self.assertEqual(len(approval_requests), 1)
        self.assertEqual(approval_requests[0]["element"]["original_message_id"], tool_calls[-1]["id"])
